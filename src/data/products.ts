export const products: Product[] = seeds.map((p, i) => ({
  id: `LW-${String(i + 1).padStart(3, "0")}`,
  slug: p[0]
    .toLowerCase()
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, "-"),
  name: p[0],
  category: p[1],
  metal: p[2],
  purity: p[3],
  gemstone: p[4],
  price: p[5],
  description: p[6],
  sizes:
    p[1] === "Rings"
      ? ["5", "6", "7", "8", "9", "10", "11"]
      : p[1] === "Bracelets"
        ? ["S", "M", "L"]
        : ["One size"],
  stock: ((i * 7) % 19) + 2,
  rating: Number((4.5 + (i % 5) * 0.1).toFixed(1)),
  images: [
    photos[i % photos.length],
    photos[(i + 1) % photos.length],
    photos[(i + 2) % photos.length],
  ],
  flag: i % 7 === 0 ? "new" : i % 4 === 0 ? "bestseller" : undefined,
}));

export const categories = [...new Set(products.map((p) => p.category))];
